-- ============================================================
-- Base de Datos: Sistema de Gestión para Gimnasio "FORJA"
-- Versión de 19 tablas — Acceso al sistema SOLO para Administrador
-- Curso: Arquitectura de Aplicaciones Web
-- Motor: PostgreSQL (13 o superior)
-- ============================================================
-- USO: crea primero la base `gimnasio_db` (clic derecho en Databases
-- -> Create -> Database), abre el Query Tool sobre ella y ejecuta
-- este script completo.
--
-- NOTA: `usuario` representa únicamente cuentas de Administrador.
-- `entrenador` es solo un dato gestionado por el admin (no inicia sesión).
-- Las columnas usan snake_case (id_usuario, fecha_registro...) y la
-- aplicación Java las mapea desde camelCase automáticamente.
-- ============================================================

-- ------------------------------------------------------------
-- 1. usuario  (ÚNICAMENTE cuentas de Administrador)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS usuario CASCADE;
CREATE TABLE usuario (
  id_usuario     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres        VARCHAR(100) NOT NULL,
  apellidos      VARCHAR(100) NOT NULL,
  dni            VARCHAR(8),
  login          VARCHAR(15) NOT NULL,
  password       VARCHAR(200) NOT NULL,
  correo         VARCHAR(45),
  telefono       VARCHAR(15),
  fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  estado         BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_usuario_login UNIQUE (login)
);

-- ------------------------------------------------------------
-- 2. entrenador  (dato gestionado por el admin, sin acceso al sistema)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS entrenador CASCADE;
CREATE TABLE entrenador (
  id_entrenador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres       VARCHAR(100) NOT NULL,
  apellidos     VARCHAR(100) NOT NULL,
  dni           VARCHAR(8),
  especialidad  VARCHAR(80),
  telefono      VARCHAR(15),
  correo        VARCHAR(45),
  estado        BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 3. cliente  (socios del gimnasio)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS cliente CASCADE;
CREATE TABLE cliente (
  id_cliente       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres          VARCHAR(100) NOT NULL,
  apellidos        VARCHAR(100) NOT NULL,
  dni              VARCHAR(8),
  correo           VARCHAR(45),
  telefono         VARCHAR(15),
  fecha_nacimiento DATE,
  direccion        TEXT,
  fecha_registro   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  estado           BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 4. actividad  (tipos de clase: Spinning, Crossfit, Yoga, etc.)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS actividad CASCADE;
CREATE TABLE actividad (
  id_actividad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(60) NOT NULL,
  descripcion  TEXT,
  estado       BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 5. horario  (sesiones de clase: actividad + entrenador + hora)
--    tipo_acceso: MEMBRESIA = incluida en el plan | LIBRE = se paga por ingreso
--    fecha: solo para clases de un día específico (ej. clase libre)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS horario CASCADE;
CREATE TABLE horario (
  id_horario     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad   INT NOT NULL,
  id_entrenador  INT NOT NULL,
  dia            VARCHAR(15) NOT NULL,
  fecha          DATE NULL,
  hora_inicio    TIME NOT NULL,
  hora_fin       TIME NOT NULL,
  cupo_maximo    INT DEFAULT 20,
  tipo_acceso    VARCHAR(10) NOT NULL DEFAULT 'MEMBRESIA',
  precio_entrada NUMERIC(8,2) NOT NULL DEFAULT 0.00,
  estado         BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_horario_actividad  FOREIGN KEY (id_actividad)  REFERENCES actividad(id_actividad),
  CONSTRAINT fk_horario_entrenador FOREIGN KEY (id_entrenador) REFERENCES entrenador(id_entrenador),
  CONSTRAINT chk_horario_tipo   CHECK (tipo_acceso IN ('MEMBRESIA','LIBRE')),
  CONSTRAINT chk_horario_horas  CHECK (hora_fin > hora_inicio),
  CONSTRAINT chk_horario_precio CHECK (precio_entrada >= 0)
);
CREATE INDEX idx_horario_actividad  ON horario(id_actividad);
CREATE INDEX idx_horario_entrenador ON horario(id_entrenador);

-- ------------------------------------------------------------
-- 6. cliente_horario  (inscripción del cliente a una sesión N:M)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS cliente_horario CASCADE;
CREATE TABLE cliente_horario (
  id_cliente_horario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente         INT NOT NULL,
  id_horario         INT NOT NULL,
  fecha_inscripcion  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  estado             BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_cliente_horario UNIQUE (id_cliente, id_horario),
  CONSTRAINT fk_clihor_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
  CONSTRAINT fk_clihor_horario FOREIGN KEY (id_horario) REFERENCES horario(id_horario)
);
CREATE INDEX idx_clihor_horario ON cliente_horario(id_horario);

-- ------------------------------------------------------------
-- 7. plan  (Quincenal, Mensual, Trimestral, Semestral, Anual)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS plan CASCADE;
CREATE TABLE plan (
  id_plan       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(60) NOT NULL,
  descripcion   TEXT,
  duracion_dias INT NOT NULL,
  precio        DOUBLE PRECISION NOT NULL,
  estado        BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 8. membresia  (contrata un plan un cliente, con vigencia)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS membresia CASCADE;
CREATE TABLE membresia (
  id_membresia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente   INT NOT NULL,
  id_plan      INT NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin    DATE NOT NULL,
  estado       BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_membresia_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
  CONSTRAINT fk_membresia_plan    FOREIGN KEY (id_plan)    REFERENCES plan(id_plan),
  CONSTRAINT chk_membresia_fechas CHECK (fecha_fin > fecha_inicio)
);
CREATE INDEX idx_membresia_cliente ON membresia(id_cliente);
CREATE INDEX idx_membresia_plan    ON membresia(id_plan);

-- ------------------------------------------------------------
-- 9. tipo_pago  (catálogo: Efectivo, Tarjeta, Yape, Plin, Transferencia)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS tipo_pago CASCADE;
CREATE TABLE tipo_pago (
  id_tipo_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(45) NOT NULL,
  estado       BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 10. pago  (1 membresía puede tener varios pagos: cuotas, etc.)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS pago CASCADE;
CREATE TABLE pago (
  id_pago      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_membresia INT NOT NULL,
  id_tipo_pago INT NOT NULL,
  monto        DOUBLE PRECISION NOT NULL,
  fecha        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  concepto     VARCHAR(100),
  CONSTRAINT fk_pago_membresia FOREIGN KEY (id_membresia) REFERENCES membresia(id_membresia),
  CONSTRAINT fk_pago_tipopago  FOREIGN KEY (id_tipo_pago) REFERENCES tipo_pago(id_tipo_pago),
  CONSTRAINT chk_pago_monto CHECK (monto > 0)
);
CREATE INDEX idx_pago_membresia ON pago(id_membresia);
CREATE INDEX idx_pago_tipopago  ON pago(id_tipo_pago);

-- ------------------------------------------------------------
-- 11. rutina  (rutina asignada por un entrenador a un cliente;
--              los ejercicios van en una columna JSONB)
--     Formato: [{"nombre","series","repeticiones","descansoSeg"}]
-- ------------------------------------------------------------
DROP TABLE IF EXISTS rutina CASCADE;
CREATE TABLE rutina (
  id_rutina      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente     INT NOT NULL,
  id_entrenador  INT NOT NULL,
  nombre         VARCHAR(80) NOT NULL,
  objetivo       VARCHAR(100),
  ejercicios     JSONB,
  fecha_creacion DATE DEFAULT CURRENT_DATE,
  estado         BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_rutina_cliente    FOREIGN KEY (id_cliente)    REFERENCES cliente(id_cliente),
  CONSTRAINT fk_rutina_entrenador FOREIGN KEY (id_entrenador) REFERENCES entrenador(id_entrenador)
);
CREATE INDEX idx_rutina_cliente    ON rutina(id_cliente);
CREATE INDEX idx_rutina_entrenador ON rutina(id_entrenador);

-- ------------------------------------------------------------
-- 12. evaluacion_fisica  (seguimiento físico del cliente en el tiempo)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS evaluacion_fisica CASCADE;
CREATE TABLE evaluacion_fisica (
  id_evaluacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente     INT NOT NULL,
  fecha          DATE DEFAULT CURRENT_DATE,
  peso           NUMERIC(5,2),
  altura         NUMERIC(4,2),
  imc            NUMERIC(4,2),
  grasa_corporal NUMERIC(4,2),
  observaciones  TEXT,
  CONSTRAINT fk_eval_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
);
CREATE INDEX idx_eval_cliente ON evaluacion_fisica(id_cliente);

-- ------------------------------------------------------------
-- 13. categoria_producto  (catálogo: Suplementos, Ropa, Accesorios...)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS categoria_producto CASCADE;
CREATE TABLE categoria_producto (
  id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(45) NOT NULL,
  estado       BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 14. producto  (tienda: suplementos, ropa, accesorios, etc.)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS producto CASCADE;
CREATE TABLE producto (
  id_producto  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria INT NOT NULL,
  nombre       VARCHAR(100) NOT NULL,
  precio       DOUBLE PRECISION NOT NULL,
  stock        INT DEFAULT 0,
  stock_minimo INT DEFAULT 5,
  estado       BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria_producto(id_categoria),
  CONSTRAINT chk_producto_precio CHECK (precio > 0)
);
CREATE INDEX idx_producto_categoria ON producto(id_categoria);

-- ------------------------------------------------------------
-- 15. venta  (cabecera de venta de productos, registrada por el admin)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS venta CASCADE;
CREATE TABLE venta (
  id_venta   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INT NOT NULL,
  id_cliente INT,
  fecha      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  total      DOUBLE PRECISION NOT NULL,
  CONSTRAINT fk_venta_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
);
CREATE INDEX idx_venta_usuario ON venta(id_usuario);
CREATE INDEX idx_venta_cliente ON venta(id_cliente);

-- ------------------------------------------------------------
-- 16. detalle_venta  (productos vendidos por venta)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS detalle_venta CASCADE;
CREATE TABLE detalle_venta (
  id_detalle      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta        INT NOT NULL,
  id_producto     INT NOT NULL,
  cantidad        INT NOT NULL,
  precio_unitario DOUBLE PRECISION NOT NULL,
  subtotal        DOUBLE PRECISION NOT NULL,
  CONSTRAINT fk_detventa_venta    FOREIGN KEY (id_venta)    REFERENCES venta(id_venta),
  CONSTRAINT fk_detventa_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto)
);
CREATE INDEX idx_detventa_venta    ON detalle_venta(id_venta);
CREATE INDEX idx_detventa_producto ON detalle_venta(id_producto);

-- ------------------------------------------------------------
-- 17. torneo  (competencias/eventos internos que organiza el gym)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS torneo CASCADE;
CREATE TABLE torneo (
  id_torneo   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(100) NOT NULL,
  descripcion TEXT,
  fecha       DATE NOT NULL,
  lugar       VARCHAR(100),
  estado      BOOLEAN NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- 18. inscripcion_torneo  (cliente inscrito a un torneo, con su
--     categoría y resultado incluidos)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS inscripcion_torneo CASCADE;
CREATE TABLE inscripcion_torneo (
  id_inscripcion    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente        INT NOT NULL,
  id_torneo         INT NOT NULL,
  id_entrenador     INT,                 -- entrenador que prepara al cliente (opcional)
  categoria         VARCHAR(60),         -- Ej: RX Masculino, RX Femenino, Scaled
  sexo              VARCHAR(10),
  peso_minimo       NUMERIC(5,2),
  peso_maximo       NUMERIC(5,2),
  fecha_inscripcion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  puesto            INT,
  puntaje           NUMERIC(6,2),
  observaciones     TEXT,
  estado            BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_inscripcion_torneo UNIQUE (id_cliente, id_torneo),
  CONSTRAINT fk_insctorneo_cliente    FOREIGN KEY (id_cliente)    REFERENCES cliente(id_cliente),
  CONSTRAINT fk_insctorneo_torneo     FOREIGN KEY (id_torneo)     REFERENCES torneo(id_torneo),
  CONSTRAINT fk_insctorneo_entrenador FOREIGN KEY (id_entrenador) REFERENCES entrenador(id_entrenador)
);
CREATE INDEX idx_insctorneo_torneo     ON inscripcion_torneo(id_torneo);
CREATE INDEX idx_insctorneo_entrenador ON inscripcion_torneo(id_entrenador);

-- ------------------------------------------------------------
-- 19. asistencia  (control de ingreso a clases por fecha.
--     Trae la actividad y el entrenador a través de horario.
--     Si la clase es LIBRE, registra cuánto pagó cada persona.)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS asistencia CASCADE;
CREATE TABLE asistencia (
  id_asistencia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_horario    INT NOT NULL,
  id_cliente    INT NOT NULL,
  id_usuario    INT NOT NULL,            -- admin que registró el ingreso
  fecha         DATE NOT NULL,           -- día concreto de la clase
  hora_ingreso  TIMESTAMP NULL,          -- se llena cuando la persona realmente entra
  estado        VARCHAR(10) NOT NULL DEFAULT 'RESERVADO',
  id_tipo_pago  INT NULL,                -- solo clases LIBRE
  monto_pagado  NUMERIC(8,2) NOT NULL DEFAULT 0.00,
  CONSTRAINT uq_asistencia UNIQUE (id_horario, id_cliente, fecha),
  CONSTRAINT fk_asist_horario  FOREIGN KEY (id_horario)   REFERENCES horario(id_horario),
  CONSTRAINT fk_asist_cliente  FOREIGN KEY (id_cliente)   REFERENCES cliente(id_cliente),
  CONSTRAINT fk_asist_usuario  FOREIGN KEY (id_usuario)   REFERENCES usuario(id_usuario),
  CONSTRAINT fk_asist_tipopago FOREIGN KEY (id_tipo_pago) REFERENCES tipo_pago(id_tipo_pago),
  CONSTRAINT chk_asist_estado CHECK (estado IN ('RESERVADO','ASISTIO','FALTO')),
  CONSTRAINT chk_asist_monto  CHECK (monto_pagado >= 0)
);
CREATE INDEX idx_asist_cliente  ON asistencia(id_cliente);
CREATE INDEX idx_asist_usuario  ON asistencia(id_usuario);
CREATE INDEX idx_asist_tipopago ON asistencia(id_tipo_pago);

